import { useEffect, useState } from 'react';
import { View, Text, StyleSheet, TouchableOpacity, ActivityIndicator, ScrollView, Platform } from 'react-native';
import { useLocalSearchParams, useRouter } from 'expo-router';
import { supabase } from '../../../lib/supabase';
import { cleanStreamTitle, getStreamCategory } from '../../../lib/categories';
import { EyeIcon, UserIcon, BroadcastIcon, MonitorIcon } from '../../../components/Icons';

function formatMomentRange(m: any) {
  const startSec = typeof m?.start_seconds === 'number' ? m.start_seconds : 0;
  const endSec = typeof m?.end_seconds === 'number' ? m.end_seconds : startSec + 30;
  const startMin = Math.floor(startSec / 60);
  const startRemainSec = startSec % 60;
  const endMin = Math.floor(endSec / 60);
  const endRemainSec = endSec % 60;

  const startStr = `${startMin}:${String(startRemainSec).padStart(2, '0')}`;
  const endStr = `${endMin}:${String(endRemainSec).padStart(2, '0')}`;
  return `${startStr} – ${endStr}`;
}

function formatSummaryText(text?: string) {
  if (!text) return '';
  return text.replace(/occurred at (\d{1,2}:\d{2})\./, (_match, p1) => {
    const parts = p1.split(':');
    const totalSec = parseInt(parts[0], 10) * 60 + parseInt(parts[1], 10);
    const endSec = totalSec + 30;
    const endStr = `${String(Math.floor(endSec / 60)).padStart(2, '0')}:${String(endSec % 60).padStart(2, '0')}`;
    return `occurred between ${p1} – ${endStr}.`;
  });
}

export default function StreamSummaryScreen() {
  const { id } = useLocalSearchParams<{ id: string }>();
  const streamId = Array.isArray(id) ? id[0] : (id || '');
  const router = useRouter();
  const [stream, setStream] = useState<any>(null);
  const [highlights, setHighlights] = useState<any>(null);

  useEffect(() => {
    if (!streamId) return;

    let timer: any = null;

    supabase
      .from('streams')
      .select('*, creator:profiles(display_name)')
      .eq('id', streamId)
      .maybeSingle()
      .then(({ data }) => setStream(data));

    supabase
      .from('stream_highlights')
      .select('*')
      .eq('stream_id', streamId)
      .maybeSingle()
      .then(({ data }) => {
        if (data) {
          setHighlights(data);
        } else {
          // Automatically synthesize highlights after 2.5s if n8n has not populated yet
          timer = setTimeout(() => {
            supabase
              .rpc('generate_stream_highlights', { p_stream_id: streamId })
              .then(({ data: generated }) => {
                if (generated) setHighlights(generated);
              });
          }, 2500);
        }
      });

    // Listen for highlights generated by n8n (Phase 3)
    const channelName = `summary:${streamId}`;
    const existing = supabase.getChannels().find((c) => c.topic === `realtime:${channelName}`);
    if (existing) {
      supabase.removeChannel(existing);
    }

    const channel = supabase
      .channel(channelName)
      .on(
        'postgres_changes',
        {
          event: '*',
          schema: 'public',
          table: 'stream_highlights',
          filter: `stream_id=eq.${streamId}`,
        },
        (payload) => {
          setHighlights(payload.new);
        }
      )
      .subscribe();

    return () => {
      if (timer) clearTimeout(timer);
      supabase.removeChannel(channel);
    };
  }, [streamId]);

  const handleManualGenerate = async () => {
    try {
      const { data, error } = await supabase.rpc('generate_stream_highlights', {
        p_stream_id: streamId,
      });
      if (!error && data) {
        setHighlights(data);
      }
    } catch (e) {
      console.log('Manual generate error:', e);
    }
  };

  const durationMins = stream?.started_at && stream?.ended_at
    ? Math.max(
        1,
        Math.round(
          (new Date(stream.ended_at).getTime() - new Date(stream.started_at).getTime()) / 60000
        )
      )
    : 0;

  return (
    <ScrollView style={styles.container} contentContainerStyle={styles.contentContainer}>
      <View style={styles.badgeRow}>
        <View style={styles.badge}>
          <Text style={styles.badgeText}>POST-EVENT ANALYTICS</Text>
        </View>
        {getStreamCategory(stream?.title) && (
          <View style={styles.categoryBadge}>
            <Text style={styles.categoryBadgeText}>
              {getStreamCategory(stream?.title)?.badge}
            </Text>
          </View>
        )}
        <View style={styles.statusPill}>
          <Text style={styles.statusText}>Concluded</Text>
        </View>
      </View>

      <Text style={styles.title}>{cleanStreamTitle(stream?.title) || 'Live Stream Concluded'}</Text>
      <Text style={styles.subtitle}>
        Broadcast telemetry and automated AI event highlight summary
      </Text>

      {/* 4 Metric Cards */}
      <View style={styles.statsGrid}>
        <View style={styles.statBox}>
          <View style={styles.iconWrap}>
            <EyeIcon size={18} color="#818CF8" />
          </View>
          <Text style={styles.statValue}>{stream?.peak_viewers ?? 0}</Text>
          <Text style={styles.statLabel}>Peak Viewers</Text>
        </View>

        <View style={styles.statBox}>
          <View style={styles.iconWrap}>
            <BroadcastIcon size={18} color="#22C55E" />
          </View>
          <Text style={styles.statValue}>{durationMins}m</Text>
          <Text style={styles.statLabel}>Total Air Time</Text>
        </View>

        <View style={styles.statBox}>
          <View style={styles.iconWrap}>
            <UserIcon size={18} color="#A78BFA" />
          </View>
          <Text style={styles.statValue} numberOfLines={1}>
            {stream?.creator?.display_name || 'Broadcaster'}
          </Text>
          <Text style={styles.statLabel}>Host Creator</Text>
        </View>

        <View style={styles.statBox}>
          <View style={styles.iconWrap}>
            <MonitorIcon size={18} color="#38BDF8" />
          </View>
          <Text style={styles.statValue}>100%</Text>
          <Text style={styles.statLabel}>Broadcast Uptime</Text>
        </View>
      </View>

      {/* AI Highlights Card */}
      <View style={styles.highlightsCard}>
        <View style={styles.highlightsHeader}>
          <View style={styles.aiBadgeTitle}>
            <View style={styles.aiIconWrap}>
              <MonitorIcon size={15} color="#818CF8" />
            </View>
            <Text style={styles.highlightsTitle}>AI Stream Highlights</Text>
          </View>
          {highlights?.summary_source && (
            <View style={styles.sourceBadge}>
              <Text style={styles.sourceText}>
                {highlights.summary_source === 'ai' ? 'AI Generated' : 'Rule-Based Recap'}
              </Text>
            </View>
          )}
        </View>

        {highlights ? (
          <View>
            <Text style={styles.summaryText}>{formatSummaryText(highlights.summary)}</Text>
            {highlights.moments && highlights.moments.length > 0 && (
              <View style={styles.momentsContainer}>
                <Text style={styles.momentsHeading}>Peak Chat Activity Moments</Text>
                {highlights.moments.map((m: any, idx: number) => (
                  <View key={idx} style={styles.momentRow}>
                    <View style={styles.momentTimestamp}>
                      <Text style={styles.timestampText}>
                        {formatMomentRange(m)}
                      </Text>
                    </View>
                    <Text style={styles.momentDesc}>
                      {m.message_count} chat messages exchanged
                    </Text>
                  </View>
                ))}
              </View>
            )}
          </View>
        ) : (
          <View style={styles.loadingHighlights}>
            <ActivityIndicator color="#818CF8" size="small" />
            <Text style={styles.loadingText}>Synthesizing stream recap and peak moments...</Text>
            <TouchableOpacity
              style={styles.generateNowBtn}
              onPress={handleManualGenerate}
              activeOpacity={0.8}
            >
              <Text style={styles.generateNowBtnText}>Generate Recap Now</Text>
            </TouchableOpacity>
          </View>
        )}
      </View>

      <TouchableOpacity
        style={styles.doneButton}
        onPress={() => router.replace('/(app)/(tabs)')}
        activeOpacity={0.85}
      >
        <Text style={styles.doneButtonText}>Return to Streams Feed</Text>
      </TouchableOpacity>
    </ScrollView>
  );
}

